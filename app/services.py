# 3. المحرك الرئيسي (AI Logic) ⚙️
# ==========================================
async def get_ai_response(user_message: str, chat_history: list):
    # إضافة رسالة المستخدم للذاكرة
    chat_history.append({"role": "user", "content": user_message})

    # الطلب الأول: الـ AI يفكر هل يحتاج أداة؟
    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=chat_history,
        tools=tools_schema,
        tool_choice="auto"
    )
    
    response_message = response.choices[0].message

    # هل قرر الـ AI استخدام أداة؟
    if response_message.tool_calls:
        tool_call = response_message.tool_calls[0]
        function_name = tool_call.function.name
        args = json.loads(tool_call.function.arguments)
        
        result = None

        # تنفيذ الأداة المناسبة
        if function_name == "get_order_status":
            result = get_order_status(args.get("phone_number"))
        elif function_name == "search_product":
            result = search_product(args.get("query"))
            
        # إضافة نتيجة الأداة للذاكرة
        chat_history.append(response_message) # طلب الأداة
        chat_history.append({
            "role": "tool",
            "tool_call_id": tool_call.id,
            "name": function_name,
            "content": result
        })
        
        # الطلب الثاني: الـ AI يقرأ النتيجة ويصيغ الرد النهائي
        final = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=chat_history
        )
        bot_reply = final.choices[0].message.content
        chat_history.append({"role": "assistant", "content": bot_reply})
        return bot_reply

    # إذا رد عادي (بدون أدوات)
    bot_reply = response_message.content
    chat_history.append({"role": "assistant", "content": bot_reply})
    return bot_reply